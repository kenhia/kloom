def bubble():
    """Alphabet's quarterly capital spending against Google Cloud's quarterly revenue, Q1 2022 to
    Q3 2026, both from its earnings releases, on an axis that starts at zero."""
    d = D()
    x0, x1, y0, y1 = 52, 372, 258, 34          # 19 quarters across; $0..$60 billion up
    n = len(ALPHABET_CAPEX)
    X = lambda i: x0 + 10 + i * (x1 - x0 - 20) / (n - 1)
    Y = lambda m: y0 - m / 60000 * (y0 - y1)
    d.group('thin')
    for v in (10000, 20000, 30000, 40000, 50000, 60000):
        d.line((x0, Y(v)), (x1, Y(v)))
    for i in range(n):
        d.line((X(i), y0), (X(i), y0 + (5 if i % 4 == 0 else 2.5)))
    d.group()
    d.line((x0, y1 - 6), (x0, y0), (x1, y0))
    d.line(*[(X(i), Y(v)) for i, v in enumerate(ALPHABET_CAPEX)])
    d.group('mid')
    cloud = [(X(i), Y(v)) for i, v in enumerate(GOOGLE_CLOUD)]
    d.dashed(*cloud, dash=4, gap=3)
    for (x, y) in cloud:
        d.circle(x, y, 1.6)
    for i, v in enumerate(ALPHABET_CAPEX):
        _box(d, X(i) - 1.6, Y(v) - 1.6, 3.2, 3.2)
    d.group('labels')
    for v, s in ((0, '0'), (20000, '20'), (40000, '40'), (60000, '60')):
        d.text(x0 - 4, Y(v) + 2.5, s, size=7, anchor='end')
    for k, yr in enumerate(range(2022, 2027)):
        d.text(X(4 * k) + 1, y0 + 14, str(yr), size=7, anchor='start')
    d.text(x0 + 4, y1 - 9, '$ BILLION A QUARTER', size=7, anchor='start')
    d.text(X(13) - 2, Y(24000), 'CAPITAL SPENDING', size=7, anchor='end')
    d.text(X(9), Y(4000), 'GOOGLE CLOUD REVENUE', size=7, anchor='start')
    d.text(x1, 290, 'ALPHABET EARNINGS RELEASES · Q1 2022–Q3 2026', size=7, anchor='end')
    return d


