def _rod(d, x, y, a, L=7):
    d.line((x - L / 2 * math.cos(a), y - L / 2 * math.sin(a)), (x + L / 2 * math.cos(a), y + L / 2 * math.sin(a)))


def koch_postulates():
    d = D()
    # Koch's proof for tuberculosis (Berlin, 24 March 1882), as a loop: the bacillus found in the
    # tissue (inside a giant cell, as he found it), grown pure on solidified blood serum in a slanted
    # tube, injected into a healthy animal, and found again in the tubercles it raised. Schematic.
    cx, cy, R = 200, 148, 96
    st = {'top': (cx, cy - R), 'right': (cx + R + 18, cy), 'bottom': (cx, cy + R), 'left': (cx - R - 18, cy)}

    d.group('thin')
    d.circle(cx, cy, R)
    for k in range(12):
        a = math.radians(k * 30)
        d.line((cx + (R - 4) * math.cos(a), cy + (R - 4) * math.sin(a)), (cx + (R + 4) * math.cos(a), cy + (R + 4) * math.sin(a)))

    d.group()
    # 1. a giant cell: a ring of nuclei, two rods inside
    gx, gy = st['top']
    d.circle(gx, gy, 21)
    # 2. a slanted tube of serum, plugged with cotton
    tx, ty = st['right']
    d.line((tx - 8, ty - 34), (tx - 8, ty + 22))
    d.line((tx + 8, ty - 34), (tx + 8, ty + 22))
    d.arc(tx, ty + 22, 8, 0, 180)
    d.line((tx - 8, ty + 4), (tx + 8, ty - 16))                            # the slant of serum
    # 3. a syringe
    sx, sy = st['bottom']
    _box(d, sx - 22, sy - 5, 36, 10)
    d.line((sx + 14, sy), (sx + 30, sy))                                   # the needle
    d.line((sx - 22, sy), (sx - 36, sy))                                   # the plunger rod
    d.line((sx - 36, sy - 6), (sx - 36, sy + 6))
    # 4. a lung lobe
    lx, ly = st['left']
    lobe = [(lx + 18 * math.cos(t) * (1 - 0.25 * math.sin(t)), ly + 26 * math.sin(t)) for t in
            (2 * math.pi * k / 48 for k in range(49))]
    d.line(*lobe)

    d.group('mid')
    for k in range(10):
        a = 2 * math.pi * k / 10
        d.ellipse(gx + 15 * math.cos(a), gy + 15 * math.sin(a), 2.6, 1.8)
    _rod(d, gx - 3, gy - 2, 0.6)
    _rod(d, gx + 4, gy + 4, -0.3)
    d.line((tx - 8, ty - 34), (tx - 5, ty - 40), (tx, ty - 37), (tx + 5, ty - 41), (tx + 8, ty - 34))
    for k in range(5):                                                     # dry, scaly colonies
        t = (k + 0.7) / 6
        px, py = tx - 8 + 16 * t, ty + 4 - 20 * t
        d.line((px - 2, py - 1), (px + 1, py - 3))
    for k in range(1, 4):
        d.line((sx - 22 + 9 * k, sy - 5), (sx - 22 + 9 * k, sy - 2))
    for (u, w) in ((-6, -10), (4, -14), (-2, 2), (7, 6), (-8, 12), (1, 16), (8, -2), (-10, -2)):
        d.circle(lx + u, ly + w, 1.8)

    d.group()
    for a0, a1 in ((-80, -10), (10, 80), (100, 170), (190, 260)):
        pts = [(cx + R * math.cos(math.radians(a0 + (a1 - a0) * i / 24)),
                cy + R * math.sin(math.radians(a0 + (a1 - a0) * i / 24))) for i in range(25)]
        _arrow(d, pts[-3], pts[-1], size=5)

    d.group('mid')
    d.text(gx + 30, gy - 14, '1 FOUND IN THE TISSUE', size=7, anchor='start')
    d.text(tx - 16, ty + 44, '2 GROWN PURE', size=7, anchor='middle')
