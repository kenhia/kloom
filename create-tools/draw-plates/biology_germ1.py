    d.text(lx - 2, ly + 40, '4 THE SAME', size=7, anchor='middle')
    d.text(lx - 2, ly + 50, 'DISEASE', size=7, anchor='middle')
    d.text(cx, cy - 4, 'TUBERCULOSIS', size=7)
    d.text(cx, cy + 8, 'BERLIN · 1882', size=7)
    return d


