"""Plates for The Story of Life's germ-theory trail, part germ1 (sprint 055): Fracastoro's three
modes of contagion, Snow's map of the Broad Street outbreak, and Koch's proof as a loop.
See plates_for.py."""
import math
from plates import D


def _arrow(d, p, q, size=5):
    """An arrowhead at q, pointing from p."""
    a = math.atan2(q[1] - p[1], q[0] - p[0])
    l = (q[0] - size * math.cos(a - 0.45), q[1] - size * math.sin(a - 0.45))
    r = (q[0] - size * math.cos(a + 0.45), q[1] - size * math.sin(a + 0.45))
    d.line(l, q, r)


def _box(d, x, y, w, h):
    d.line((x, y), (x + w, y), (x + w, y + h), (x, y + h), closed=True)


# --- fracastoro --------------------------------------------------------------------------------

def _figure(d, x, y):
    """A person as geometry: a head and a tapered body standing on y."""
    d.circle(x, y - 40, 6)
    d.line((x - 12, y), (x - 9, y - 26), (x - 4, y - 31), (x + 4, y - 31), (x + 9, y - 26), (x + 12, y))


def _seeds(d, pts, r=1.3):
    for x, y in pts:
        d.circle(x, y, r)


def fracastoro():
    d = D()
    # De contagione I.2 (Venice, 1546): contagion passes by contact alone (his example is fruit,
    # grape to grape), by contact and fomites (clothes, wood), and also at a distance, through the
    # air. The seminaria are drawn as dots: he never saw them, and their size here is arbitrary.
    rows = (84, 172, 260)
    left, right = 70, 330

    d.group('thin')
    for y in rows:
        d.line((30, y), (370, y))                                          # each row's ground
    d.dashed((left, 120), (left, 270), dash=2, gap=4)
    d.dashed((right, 120), (right, 270), dash=2, gap=4)
    for gx in range(110, 300, 24):                                         # the air of row three
        for gy in range(212, 252, 12):
            d.line((gx - 1, gy), (gx + 1, gy))

    d.group()
    # row one: two grapes on a stalk, touching; the rot crosses where they meet
    g1, g2, gy, gr = (183, 58), (217, 58), 58, 17
    d.circle(*g1, gr)
    d.circle(*g2, gr)
    d.line((200, gy - gr - 20), (200, gy - gr - 10))                       # the stalk
    d.curve(f'M200 {gy - gr - 10} Q{g1[0]} {gy - gr - 8} {g1[0]} {gy - gr}')
    d.curve(f'M200 {gy - gr - 10} Q{g2[0]} {gy - gr - 8} {g2[0]} {gy - gr}')
    # row two: a person, a cloth, a person
    _figure(d, left, rows[1])
    _figure(d, right, rows[1])
    cx, cy = 200, rows[1] - 18
    d.line((cx - 26, cy - 10), (cx + 26, cy - 10), (cx + 30, cy + 14), (cx - 30, cy + 14), closed=True)
    # row three: a person, the air, a person
    _figure(d, left, rows[2])
    _figure(d, right, rows[2])

    d.group('mid')
    for k in range(1, 6):                                                  # the cloth's weave
        x = cx - 26 + k * 52 / 6
        d.line((x, cy - 10), (x + 4 * (k - 3) / 3, cy + 14))
    d.line((cx - 28, cy + 2), (cx + 28, cy + 2))
    d.arc(g1[0], gy, gr - 6, -60, 60)                                      # the rotten patch
    d.arc(g2[0], gy, gr - 6, 120, 240)
    for a, b in (((left + 18, rows[1] - 24), (cx - 34, cy)), ((cx + 34, cy), (right - 18, rows[1] - 24))):
        d.line(a, b)
        _arrow(d, a, b, size=4)
    path = [(left + 16 + t * (right - left - 32), rows[2] - 36 - 16 * math.sin(math.pi * t)) for t in
            (i / 40 for i in range(41))]
    d.dashed(*path, dash=3, gap=3)
    _arrow(d, path[-3], path[-1], size=4)

    d.group()
    _seeds(d, [(200 + 2 * math.cos(k), 52 + 9 * k / 5) for k in range(6)], r=1.1)
    _seeds(d, [(cx - 14, cy - 3), (cx + 9, cy - 4), (cx - 3, cy + 7), (cx + 17, cy + 8), (cx - 20, cy + 9)])
    _seeds(d, [path[i] for i in (7, 13, 20, 27, 33)])

    d.group('mid')
    d.text(30, 22, 'BY CONTACT · GRAPE TO GRAPE', size=7, anchor='start')
    d.text(30, 110, 'BY FOMITES · CLOTHES, WOOD', size=7, anchor='start')
    d.text(30, 198, 'AT A DISTANCE · THROUGH THE AIR', size=7, anchor='start')
    d.text(200, 286, 'DE CONTAGIONE I.2 · VENICE, 1546', size=7)
    d.text(right + 20, 30, 'SEMINARIA', size=7, anchor='start')
    d.circle(right + 14, 27.5, 1.3)
    return d


