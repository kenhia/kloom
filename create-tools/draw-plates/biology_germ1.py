PUMPS = [('Oxford Market', 8.65, 17.89), ('Castle St E', 10.98, 18.52), ('Oxford St #1', 13.38, 17.39), ('Oxford St #2', 14.88, 17.81), ('Gt Marlborough', 8.69, 14.91), ('Crown Chapel', 8.86, 12.75), ('Broad St', 12.57, 11.73), ('Warwick', 10.66, 7.43), ('Briddle St', 13.52, 7.96), ('So Soho', 16.43, 9.25), ('Dean St', 18.91, 9.74), ('Coventry St', 16.01, 5.05), ('Vigo St', 9.0, 5.1)]

_X0, _X1, _Y0, _Y1 = 7.6, 18.6, 5.4, 17.6     # the window drawn, in the data's units
_S, _MX, _MY = 21.4, 16, 18                    # plate units per data unit, and the map's corner


def _xy(x, y):
    return (_MX + (x - _X0) * _S, _MY + (_Y1 - y) * _S)


def _nums(s):
    return [int(v) / 100 for v in s.replace(',', ' ').split()]


def _cell(site, others):
    """The region nearer `site` than any other point (a Voronoi cell), clipped to the window."""
    poly = [(_X0, _Y0), (_X1, _Y0), (_X1, _Y1), (_X0, _Y1)]
    for o in others:
        mx, my = (site[0] + o[0]) / 2, (site[1] + o[1]) / 2
        nx, ny = o[0] - site[0], o[1] - site[1]
        side = lambda p: (p[0] - mx) * nx + (p[1] - my) * ny              # < 0 on site's side
        out = []
        for a, b in zip(poly, poly[1:] + poly[:1]):
            sa, sb = side(a), side(b)
            if sa <= 0:
                out.append(a)
            if sa * sb < 0:
                t = sa / (sa - sb)
                out.append((a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])))
        poly = out
    return poly


def snow_pump():
    d = D()
    s = _nums(STREETS)
    segs = [((s[i], s[i + 1]), (s[i + 2], s[i + 3])) for i in range(0, len(s), 4)]
    v = _nums(DEATHS)
    deaths = [(v[i], v[i + 1]) for i in range(0, len(v), 2)]
    pumps = [(x, y) for _, x, y in PUMPS]
    broad = pumps[6]

    def along(p):
        """The direction of the street nearest p, so a death's bar lies along it, as Snow drew it."""
        best, ang = 1e9, 0.0
        for a, b in segs:
            dx, dy = b[0] - a[0], b[1] - a[1]
            L2 = dx * dx + dy * dy
            t = max(0.0, min(1.0, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / L2))
            q = (a[0] + t * dx, a[1] + t * dy)
            dist = math.dist(p, q)
            if dist < best:
                best, ang = dist, math.atan2(-dy, dx)
        return ang

    d.group('thin')
    cell = [_xy(*p) for p in _cell(broad, [p for p in pumps if p != broad])]
    d.dashed(*cell, cell[0], dash=3, gap=3)                               # nearer this pump than any
    for k in range(6):                                                    # a 100 m scale
        d.line(_xy(_X0 + 0.3 + k * 0.2, _Y0 + 0.35), _xy(_X0 + 0.3 + k * 0.2, _Y0 + 0.5))

    d.group('mid')
    d.lines([[_xy(*a), _xy(*b)] for a, b in segs])
    d.line(_xy(_X0 + 0.3, _Y0 + 0.35), _xy(_X0 + 1.3, _Y0 + 0.35))

    d.group()
    ticks = []
    for p in deaths:
        cx, cy = _xy(*p)
        a = along(p)
        ticks.append([(cx - 1.3 * math.cos(a), cy - 1.3 * math.sin(a)), (cx + 1.3 * math.cos(a), cy + 1.3 * math.sin(a))])
    d.lines(ticks)

    d.group()
    for p in pumps:
        if not (_X0 < p[0] < _X1 and _Y0 < p[1] < _Y1):
            continue
        x, y = _xy(*p)
        d.circle(x, y, 2.6 if p != broad else 4.5)
    bx, by = _xy(*broad)
    d.circle(bx, by, 8)

    d.group('mid')
    lx = _MX + (_X1 - _X0) * _S + 14
